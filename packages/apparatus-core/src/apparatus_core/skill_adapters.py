"""Managed native Skill pointer adapters for Apparatus work areas and bound projects."""

from __future__ import annotations

from collections.abc import Callable, Iterable
from contextlib import ExitStack
from dataclasses import dataclass
import errno
import os
from pathlib import Path, PurePosixPath
import re
import stat
import unicodedata

from apparatus_core import learned_skills, records, skills
from apparatus_core.fs_transactions import WorkspaceAnchor
from apparatus_core.init_deploy import _anchor_child
from apparatus_core.payload import PayloadError, preflight_workspace_paths
from apparatus_core.render import is_reparse_path

WORK_AREA_ADAPTER_PREFIXES: tuple[str, ...] = (".claude/skills",)
PROJECT_ADAPTER_PREFIXES: tuple[str, ...] = (".agents/skills", ".claude/skills")

_ADAPTER_HEADER = "# Generated by apparatus render. Do not edit by hand."
_ADAPTER_MARKER = "<!-- apparatus:skill-adapter -->"
_WINDOWS_INVALID_CHARACTERS = frozenset('<>:"|?*\\')
_WINDOWS_RESERVED_BASENAMES = frozenset(
    (
        "con",
        "prn",
        "aux",
        "nul",
        *(f"com{number}" for number in range(1, 10)),
        *(f"lpt{number}" for number in range(1, 10)),
    )
)
_PROJECT_CANONICAL_RE = re.compile(
    r"Read the canonical Skill instructions at `((?:\.\./){1,64}\.agents/skills/([a-z0-9-]+)/SKILL\.md)` and follow them\."
)


class SkillAdapterError(ValueError):
    """Native Skill adapters could not be planned or published safely."""


@dataclass(frozen=True)
class QualifyingSkill:
    """One canonical Skill eligible for native pointer adapters."""

    name: str
    description: str
    body_relative: str


@dataclass(frozen=True)
class AdapterSyncResult:
    """Deterministic outcome of synchronizing native Skill adapters in one root."""

    written: tuple[str, ...] = ()
    unchanged: tuple[str, ...] = ()
    removed: tuple[str, ...] = ()
    conflicts: tuple[str, ...] = ()

    @property
    def actions(self) -> tuple[tuple[str, str], ...]:
        return (
            *(("written", target) for target in self.written),
            *(("unchanged", target) for target in self.unchanged),
            *(("removed", target) for target in self.removed),
        )


@dataclass(frozen=True)
class AdapterFinding:
    """One native Skill adapter verification finding."""

    code: str
    path: str
    hint: str


def conflict_notice(relative: str) -> str:
    """Return user-facing reconciliation guidance for an occupied adapter path."""
    return (
        f"conflict {relative}: unrecognized entry occupies this native Skill adapter path; "
        f"preserve or remove it, then run `apparatus render`."
    )


def _portable_component_key(component: str) -> str:
    return unicodedata.normalize("NFC", component).casefold()


def _validate_component(component: str, label: str) -> None:
    if (
        not component
        or component in {".", ".."}
        or any(ord(ch) < 32 or ch == "/" or ch in _WINDOWS_INVALID_CHARACTERS for ch in component)
        or component[-1] in {" ", "."}
    ):
        raise SkillAdapterError(f"{label} {component!r} is not a portable path component.")
    stem = component.split(".", 1)[0].casefold()
    if stem in _WINDOWS_RESERVED_BASENAMES:
        raise SkillAdapterError(f"{label} {component!r} uses a Windows-reserved device name.")


def _validate_relative_workspace(relative_workspace: str) -> str:
    raw = relative_workspace.replace("\\", "/")
    parts = PurePosixPath(raw).parts
    if not parts or len(parts) > 64 or any(part != ".." for part in parts) or "/".join(parts) != raw:
        raise SkillAdapterError("Project binding has an invalid relative work-area path.")
    return raw


def canonical_relative_path(name: str, *, relative_workspace: str | None = None) -> str:
    """Build the portable forward-slash relative path to the canonical Skill body."""
    if not skills.valid_name(name):
        raise SkillAdapterError(f"Skill name {name!r} is not valid.")
    _validate_component(name, "Skill name")
    body_rel = skills.canonical_path(name)
    if relative_workspace is None:
        return body_rel
    validated = _validate_relative_workspace(relative_workspace)
    return f"{validated}/{body_rel}"


def parse_adapter_target(relative: str, *, prefixes: tuple[str, ...]) -> tuple[str, str] | None:
    """Return (prefix, skill_name) when *relative* matches a managed adapter target."""
    path = PurePosixPath(relative)
    if len(path.parts) != 4 or path.name != "SKILL.md":
        return None
    prefix = "/".join(path.parts[:2])
    name = path.parts[2]
    if prefix not in prefixes or not skills.valid_name(name):
        return None
    return prefix, name


def render_adapter_bytes(name: str, description: str, canonical_rel: str) -> bytes:
    """Render deterministic UTF-8 pointer adapter bytes for a qualifying Skill."""
    frontmatter = records.yaml.safe_dump(
        {"name": name, "description": description},
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=4096,
    )
    text = (
        f"---\n"
        f"{_ADAPTER_HEADER}\n"
        f"{frontmatter}"
        f"---\n\n"
        f"{_ADAPTER_MARKER}\n"
        f"Generated by `apparatus render`. Do not edit this file by hand.\n\n"
        f"Read the canonical Skill instructions at `{canonical_rel}` and follow them.\n"
        f"`{canonical_rel}` is the single editable source for this Skill.\n"
        f"If `{canonical_rel}` cannot be read, say so clearly and continue without this Skill.\n"
    )
    return text.encode("utf-8")


def _extract_skill_metadata(content: bytes, expected_name: str) -> tuple[str, str] | None:
    if skills.validate_skill(content, expected_name):
        return None
    text = content.decode("utf-8")
    lines = text.splitlines(keepends=True)
    closing = next(i for i in range(1, len(lines)) if lines[i].rstrip("\r\n") == "---")
    data = records.yaml.safe_load("".join(lines[1:closing]))
    if not isinstance(data, dict):
        return None
    name = data.get("name")
    description = data.get("description")
    if not isinstance(name, str) or not isinstance(description, str):
        return None
    return name, description


def _normalize_line_endings(content: bytes) -> bytes | None:
    if b"\r\n" not in content:
        return None if b"\r" in content else content
    normalized = content.replace(b"\r\n", b"\n")
    if normalized.replace(b"\n", b"\r\n") != content:
        return None
    return normalized


def owns_adapter(
    content: bytes,
    target_rel: str,
    *,
    is_project: bool = False,
    expected_relative_workspace: str | None = None,
) -> bool:
    """Return True only when *content* matches full generated adapter bytes (LF or CRLF)."""
    prefixes = PROJECT_ADAPTER_PREFIXES if is_project else WORK_AREA_ADAPTER_PREFIXES
    parsed_target = parse_adapter_target(target_rel, prefixes=prefixes)
    if parsed_target is None:
        return False
    _, dir_name = parsed_target
    try:
        _validate_component(dir_name, "Skill name")
    except SkillAdapterError:
        return False
    normalized = _normalize_line_endings(content)
    if normalized is None:
        return False
    metadata = _extract_skill_metadata(normalized, dir_name)
    if metadata is None:
        return False
    name, description = metadata
    try:
        text = normalized.decode("utf-8")
    except UnicodeError:
        return False
    lines = text.splitlines(keepends=True)
    closing = next((i for i in range(1, len(lines)) if lines[i].rstrip("\r\n") == "---"), None)
    if closing is None:
        return False
    header_data = records.yaml.safe_load("".join(lines[1:closing]))
    if not isinstance(header_data, dict) or set(header_data) != {"name", "description"}:
        return False

    candidates: list[str] = []
    if not is_project:
        candidates.append(canonical_relative_path(name))
    else:
        if expected_relative_workspace is not None:
            candidates.append(canonical_relative_path(name, relative_workspace=expected_relative_workspace))
        for match in _PROJECT_CANONICAL_RE.finditer(text):
            if match.group(2) == name and match.group(1) not in candidates:
                candidates.append(match.group(1))
    return any(normalized == render_adapter_bytes(name, description, rel) for rel in candidates)


def _reject_case_unicode_collisions(names: Iterable[str]) -> None:
    seen: dict[str, str] = {}
    for name in names:
        key = _portable_component_key(name)
        previous = seen.get(key)
        if previous is not None and previous != name:
            raise SkillAdapterError(
                f"Skill names {previous!r} and {name!r} collide under case or Unicode normalization."
            )
        seen[key] = name


def _find_entry_exact_or_collision(parent_dir: Path, expected_name: str, display_path: str) -> str | None:
    """Return 'exact', 'collision', or None without following symlinks."""
    expected_key = _portable_component_key(expected_name)
    exact_found = False
    try:
        with os.scandir(parent_dir) as entries:
            for entry in entries:
                if entry.name == expected_name:
                    exact_found = True
                elif _portable_component_key(entry.name) == expected_key:
                    raise SkillAdapterError(
                        f"workspace path {display_path!r} collides with existing {entry.name!r}."
                    )
    except OSError as error:
        if error.errno == errno.ENOENT:
            return None
        raise SkillAdapterError(f"could not inspect directory {parent_dir.name!r}") from error
    return "exact" if exact_found else None


def _inspect_parent_chain(root: Path, parent_parts: tuple[str, ...]) -> bool:
    """Validate existing parent directories cleanly; return True if full chain exists."""
    current = root
    for index, part in enumerate(parent_parts):
        _validate_component(part, "adapter directory")
        display = "/".join(parent_parts[: index + 1])
        match = _find_entry_exact_or_collision(current, part, display)
        if match is None:
            return False
        candidate = current / part
        try:
            st = os.lstat(candidate)
        except OSError as error:
            raise SkillAdapterError(f"workspace path {display!r} could not be inspected.") from error
        if stat.S_ISLNK(st.st_mode) or is_reparse_path(candidate):
            raise SkillAdapterError(f"workspace path {display!r} must not be a symbolic link or reparse point.")
        if not stat.S_ISDIR(st.st_mode):
            raise SkillAdapterError(f"workspace path {display!r} must be a directory.")
        current = candidate
    return True


def _inspect_target_entry(root: Path, relative: str) -> str:
    """Inspect one adapter target safely: returns 'missing', 'file', or 'occupant'."""
    parts = PurePosixPath(relative).parts
    if not _inspect_parent_chain(root, parts[:-1]):
        return "missing"
    parent_dir = root.joinpath(*parts[:-1])
    leaf_name = parts[-1]
    _validate_component(leaf_name, "adapter filename")
    match = _find_entry_exact_or_collision(parent_dir, leaf_name, relative)
    if match is None:
        return "missing"
    leaf_path = parent_dir / leaf_name
    try:
        st = os.lstat(leaf_path)
    except OSError as error:
        raise SkillAdapterError(f"workspace path {relative!r} could not be inspected.") from error
    if stat.S_ISLNK(st.st_mode) or is_reparse_path(leaf_path) or stat.S_ISDIR(st.st_mode) or not stat.S_ISREG(st.st_mode):
        return "occupant"
    return "file"


def discover_qualifying_skills(
    anchor: WorkspaceAnchor,
    *,
    excluded: Callable[[str], bool] | None = None,
    ignored_names: set[str] | None = None,
) -> tuple[QualifyingSkill, ...]:
    """Read built-in and adopted learned Skills eligible for pointer adapters."""
    qualifying: dict[str, QualifyingSkill] = {}

    for builtin_rel, name in sorted(skills.BUILTIN_PATHS.items(), key=lambda item: item[1]):
        _validate_component(name, "Skill name")
        if excluded is not None and excluded(builtin_rel):
            if ignored_names is not None:
                ignored_names.add(name)
            continue
        try:
            content, _ = anchor.read_file(builtin_rel)
        except FileNotFoundError:
            continue
        except OSError as error:
            raise SkillAdapterError(f"built-in Skill {builtin_rel!r} is unsafe to read.") from error
        metadata = _extract_skill_metadata(content, name)
        if metadata is not None:
            _, description = metadata
            qualifying[name] = QualifyingSkill(name=name, description=description, body_relative=builtin_rel)

    try:
        has_adopted = anchor.directory_exists(learned_skills.ADOPTED)
    except OSError as error:
        raise SkillAdapterError("adopted Skill ownership directory is unsafe to inspect.") from error

    if has_adopted and not (excluded is not None and excluded(learned_skills.ADOPTED)):
        try:
            marker_paths = anchor.list_files(learned_skills.ADOPTED, suffix=".yaml", include_hidden=False)
        except OSError as error:
            raise SkillAdapterError("adopted Skill ownership directory could not be listed safely.") from error
        for marker_rel in sorted(marker_paths, key=lambda path: path.as_posix()):
            marker_posix = marker_rel.as_posix()
            if excluded is not None and excluded(marker_posix):
                identity = learned_skills.path_kind(marker_posix)
                if identity is not None and ignored_names is not None:
                    ignored_names.add(identity[1])
                continue
            try:
                marker_bytes, _ = anchor.read_file(marker_posix)
            except FileNotFoundError:
                continue
            except OSError as error:
                raise SkillAdapterError(f"adopted Skill marker {marker_posix!r} is unsafe to read.") from error
            try:
                name = learned_skills.parse_marker(marker_posix, marker_bytes)
            except learned_skills.LearnedSkillError:
                continue
            _validate_component(name, "Skill name")
            body_rel = learned_skills.body_path(name)
            if excluded is not None and excluded(body_rel):
                if ignored_names is not None:
                    ignored_names.add(name)
                continue
            try:
                body_bytes, _ = anchor.read_file(body_rel)
            except FileNotFoundError:
                continue
            except OSError as error:
                raise SkillAdapterError(f"adopted Skill body {body_rel!r} is unsafe to read.") from error
            metadata = _extract_skill_metadata(body_bytes, name)
            if metadata is not None:
                _, description = metadata
                qualifying[name] = QualifyingSkill(name=name, description=description, body_relative=body_rel)

    _reject_case_unicode_collisions(qualifying.keys())
    return tuple(qualifying[name] for name in sorted(qualifying))


def _scan_prefix_skill_files(root: Path, prefix: str) -> tuple[str, ...]:
    """Enumerate depth-2 `<prefix>/<name>/SKILL.md` regular files without following symlinks."""
    prefix_parts = PurePosixPath(prefix).parts
    if not _inspect_parent_chain(root, prefix_parts):
        return ()
    prefix_dir = root.joinpath(*prefix_parts)
    candidates: list[str] = []
    try:
        with os.scandir(prefix_dir) as entries:
            subdirs = sorted((entry for entry in entries), key=lambda entry: entry.name)
    except OSError as error:
        raise SkillAdapterError(f"could not inspect adapter directory {prefix!r}") from error
    for entry in subdirs:
        if entry.name.startswith("."):
            continue
        subdir_path = prefix_dir / entry.name
        try:
            st = os.lstat(subdir_path)
        except OSError:
            continue
        if stat.S_ISLNK(st.st_mode) or is_reparse_path(subdir_path) or not stat.S_ISDIR(st.st_mode):
            continue
        if not skills.valid_name(entry.name):
            continue
        leaf_rel = f"{prefix}/{entry.name}/SKILL.md"
        leaf_path = subdir_path / "SKILL.md"
        try:
            leaf_st = os.lstat(leaf_path)
        except FileNotFoundError:
            continue
        except OSError:
            continue
        if stat.S_ISLNK(leaf_st.st_mode) or is_reparse_path(leaf_path) or not stat.S_ISREG(leaf_st.st_mode):
            continue
        try:
            match = _find_entry_exact_or_collision(subdir_path, "SKILL.md", leaf_rel)
        except SkillAdapterError:
            continue
        if match == "exact":
            candidates.append(leaf_rel)
    return tuple(candidates)


def preflight_adapters(target_root: str | Path, *, is_project: bool = False) -> Path:
    """Validate root and any existing adapter prefix directories without writing."""
    try:
        root = preflight_workspace_paths(target_root)
    except (PayloadError, OSError) as error:
        raise SkillAdapterError(f"target root is unsafe for native Skill adapters: {error}") from error
    prefixes = PROJECT_ADAPTER_PREFIXES if is_project else WORK_AREA_ADAPTER_PREFIXES
    for prefix in prefixes:
        _inspect_parent_chain(root, PurePosixPath(prefix).parts)
    return root


def _try_remove_empty_adapter_dirs(anchor: WorkspaceAnchor, removed_relatives: Iterable[str]) -> None:
    """Remove adapter parent directories left empty after removing owned adapters."""
    parents: set[Path] = set()
    for relative in removed_relatives:
        rel_path = Path(relative)
        for parent in rel_path.parents:
            if parent != Path("."):
                parents.add(parent)
    for parent in sorted(parents, key=lambda item: (len(item.parts), item.as_posix()), reverse=True):
        try:
            if not anchor.root_is_current() or not anchor.directory_exists(parent):
                continue
        except OSError:
            continue
        dir_path = anchor.workspace / parent
        if is_reparse_path(dir_path):
            continue
        try:
            with os.scandir(dir_path) as entries:
                if any(True for _ in entries):
                    continue
            os.rmdir(dir_path)
        except OSError:
            continue


def _sync_adapters(
    target_root: str | Path,
    work_area_root: str | Path,
    *,
    is_project: bool,
    relative_workspace: str | None = None,
) -> AdapterSyncResult:
    target_path = preflight_adapters(target_root, is_project=is_project)
    try:
        source_path = preflight_workspace_paths(work_area_root)
    except (PayloadError, OSError) as error:
        raise SkillAdapterError(f"work area is unsafe for native Skill adapters: {error}") from error
    if is_project:
        if relative_workspace is None:
            raise SkillAdapterError("Bound project adapter sync requires relative_workspace.")
        _validate_relative_workspace(relative_workspace)

    prefixes = PROJECT_ADAPTER_PREFIXES if is_project else WORK_AREA_ADAPTER_PREFIXES
    with ExitStack() as stack:
        target_anchor = stack.enter_context(WorkspaceAnchor(target_path))
        source_anchor = (
            target_anchor
            if not is_project
            else stack.enter_context(WorkspaceAnchor(source_path))
        )
        qualifying = discover_qualifying_skills(source_anchor)
        desired: dict[str, bytes] = {}
        for skill in qualifying:
            canonical_rel = canonical_relative_path(
                skill.name,
                relative_workspace=relative_workspace if is_project else None,
            )
            content = render_adapter_bytes(skill.name, skill.description, canonical_rel)
            for prefix in prefixes:
                desired[f"{prefix}/{skill.name}/SKILL.md"] = content

        to_create: list[tuple[str, bytes]] = []
        to_replace: list[tuple[str, object, bytes, bytes]] = []
        to_remove: list[tuple[str, object, bytes]] = []
        unchanged: list[str] = []
        conflicts: list[str] = []

        for target_rel in sorted(desired):
            desired_bytes = desired[target_rel]
            state = _inspect_target_entry(target_path, target_rel)
            if state == "missing":
                to_create.append((target_rel, desired_bytes))
                continue
            if state == "occupant":
                conflicts.append(target_rel)
                continue
            owned = target_anchor.capture_file(target_rel, publication_compatible=True)
            try:
                current_identity = owned.identity
                current_bytes = owned.content
            finally:
                owned.close()
            if not owns_adapter(
                current_bytes,
                target_rel,
                is_project=is_project,
                expected_relative_workspace=relative_workspace if is_project else None,
            ):
                conflicts.append(target_rel)
            elif current_bytes == desired_bytes:
                unchanged.append(target_rel)
            else:
                to_replace.append((target_rel, current_identity, current_bytes, desired_bytes))

        for prefix in prefixes:
            for existing_rel in _scan_prefix_skill_files(target_path, prefix):
                if existing_rel in desired:
                    continue
                owned = target_anchor.capture_file(existing_rel, publication_compatible=True)
                try:
                    current_identity = owned.identity
                    current_bytes = owned.content
                finally:
                    owned.close()
                if owns_adapter(
                    current_bytes,
                    existing_rel,
                    is_project=is_project,
                    expected_relative_workspace=relative_workspace if is_project else None,
                ):
                    to_remove.append((existing_rel, current_identity, current_bytes))

        if not to_create and not to_replace and not to_remove:
            return AdapterSyncResult(
                written=(),
                unchanged=tuple(sorted(unchanged)),
                removed=(),
                conflicts=tuple(sorted(conflicts)),
            )

        _publish_changes(
            target_anchor,
            source_anchor,
            to_create=to_create,
            to_replace=to_replace,
            to_remove=to_remove,
        )
        written = sorted([*(rel for rel, _ in to_create), *(rel for rel, _, _, _ in to_replace)])
        removed = sorted(rel for rel, _, _ in to_remove)
        return AdapterSyncResult(
            written=tuple(written),
            unchanged=tuple(sorted(unchanged)),
            removed=tuple(removed),
            conflicts=tuple(sorted(conflicts)),
        )


def _publish_changes(
    target_anchor: WorkspaceAnchor,
    source_anchor: WorkspaceAnchor,
    *,
    to_create: list[tuple[str, bytes]],
    to_replace: list[tuple[str, object, bytes, bytes]],
    to_remove: list[tuple[str, object, bytes]],
) -> None:
    """Apply creates, preimage-checked replacements, and preimage-checked removals."""
    created_files: list[tuple[WorkspaceAnchor, object]] = []
    created_dirs: list[tuple[WorkspaceAnchor, object, WorkspaceAnchor]] = []
    transactions: list[object] = []
    staged_removals: list[object] = []
    anchors: dict[Path, WorkspaceAnchor] = {Path("."): target_anchor}
    committed = False

    with ExitStack() as stack:
        try:
            needed_dirs = sorted(
                {
                    parent
                    for rel, _ in to_create
                    for parent in Path(rel).parents
                    if parent != Path(".")
                },
                key=lambda path: (len(path.parts), path.as_posix()),
            )
            for rel_dir in needed_dirs:
                parent_rel = rel_dir.parent
                parent_anchor = anchors[parent_rel]
                parent_path = (
                    target_anchor.workspace
                    if parent_rel == Path(".")
                    else target_anchor.workspace / parent_rel
                )
                child_anchor, created_owned, _ = _anchor_child(parent_anchor, parent_path, rel_dir.name)
                anchors[rel_dir] = child_anchor
                stack.callback(child_anchor.close)
                if created_owned is not None:
                    created_dirs.append((parent_anchor, created_owned, child_anchor))

            for rel, desired_bytes in to_create:
                rel_path = Path(rel)
                parent_anchor = anchors[rel_path.parent]
                created_file = parent_anchor.create_file(rel_path.name, desired_bytes, mode=0o644)
                created_files.append((parent_anchor, created_file))

            for rel, identity, old_bytes, new_bytes in to_replace:
                tx = target_anchor.replace_if_unchanged(rel, identity, old_bytes, new_bytes)
                transactions.append(tx)

            for rel, identity, expected_bytes in to_remove:
                owned = target_anchor.capture_file(rel)
                if owned.identity != identity or owned.content != expected_bytes:
                    owned.close()
                    raise SkillAdapterError(f"adapter {rel!r} changed before removal; retry.")
                staged_removals.append(owned)

            if not target_anchor.root_is_current() or not source_anchor.root_is_current():
                raise SkillAdapterError("workspace root changed during adapter publication.")
            for tx in transactions:
                tx.validate_commit()

            for tx in transactions:
                tx.commit()
                tx.close()
            for _, created_file in created_files:
                created_file.close()
            for _, created_owned, _ in created_dirs:
                created_owned.close()
            for owned in staged_removals:
                target_anchor.unlink_owned(owned)
                owned.close()
            committed = True
        except Exception as error:
            for owned in staged_removals:
                try:
                    owned.close()
                except Exception:
                    pass
            for tx in reversed(transactions):
                try:
                    tx.rollback()
                except Exception:
                    pass
                try:
                    tx.close()
                except Exception:
                    pass
            for parent_anchor, created_file in reversed(created_files):
                try:
                    parent_anchor.unlink_owned_if_present(created_file)
                except Exception:
                    pass
                try:
                    created_file.close()
                except Exception:
                    pass
            for parent_anchor, created_owned, child_anchor in reversed(created_dirs):
                try:
                    child_anchor.close()
                except Exception:
                    pass
                try:
                    parent_anchor.remove_owned_directory(created_owned)
                except Exception:
                    pass
                try:
                    created_owned.close()
                except Exception:
                    pass
            if isinstance(error, SkillAdapterError):
                raise
            raise SkillAdapterError(f"could not safely publish native Skill adapters: {error}") from error

    if committed and to_remove:
        _try_remove_empty_adapter_dirs(target_anchor, (rel for rel, _, _ in to_remove))


def sync_work_area_adapters(work_area: str | Path) -> AdapterSyncResult:
    """Synchronize `.claude/skills/<NAME>/SKILL.md` adapters in one work area."""
    return _sync_adapters(work_area, work_area, is_project=False)


