def remove_owned_adapters(
    target_root: str | Path,
    *,
    is_project: bool = False,
    expected_relative_workspace: str | None = None,
) -> AdapterSyncResult:
    """Remove only Apparatus-owned native Skill adapters and directories left empty."""
    target_path = preflight_adapters(target_root, is_project=is_project)
    prefixes = PROJECT_ADAPTER_PREFIXES if is_project else WORK_AREA_ADAPTER_PREFIXES
    to_remove: list[tuple[str, object, bytes]] = []
    with WorkspaceAnchor(target_path) as target_anchor:
        for prefix in prefixes:
            for existing_rel in _scan_prefix_skill_files(target_path, prefix):
                owned = target_anchor.capture_file(existing_rel, publication_compatible=True)
                try:
                    identity = owned.identity
                    content = owned.content
                finally:
                    owned.close()
                if owns_adapter(
                    content,
                    existing_rel,
                    is_project=is_project,
                    expected_relative_workspace=expected_relative_workspace,
                ):
                    to_remove.append((existing_rel, identity, content))

        if not to_remove:
            return AdapterSyncResult()

        staged: list[object] = []
        try:
            for rel, identity, expected_bytes in to_remove:
                owned = target_anchor.capture_file(rel)
                if owned.identity != identity or owned.content != expected_bytes:
                    owned.close()
                    raise SkillAdapterError(f"adapter {rel!r} changed before removal; retry.")
                staged.append(owned)
            if not target_anchor.root_is_current():
                raise SkillAdapterError("target root changed during adapter removal.")
            for owned in staged:
                target_anchor.unlink_owned(owned)
                owned.close()
        except Exception as error:
            for owned in staged:
                try:
                    owned.close()
                except Exception:
                    pass
            if isinstance(error, SkillAdapterError):
                raise
            raise SkillAdapterError(f"could not remove owned native Skill adapters: {error}") from error

        _try_remove_empty_adapter_dirs(target_anchor, (rel for rel, _, _ in to_remove))

    return AdapterSyncResult(removed=tuple(sorted(rel for rel, _, _ in to_remove)))


def check_adapter_findings(
    target_root: str | Path,
    work_area_root: str | Path,
    *,
    relative_workspace: str | None = None,
    excluded: Callable[[str], bool] | None = None,
) -> tuple[AdapterFinding, ...]:
    """Check native Skill adapters in one root iff >= 1 Apparatus-owned adapter exists."""
    is_project = relative_workspace is not None
    prefixes = PROJECT_ADAPTER_PREFIXES if is_project else WORK_AREA_ADAPTER_PREFIXES
    repair_cmd = "apparatus render PROJECT" if is_project else "apparatus render WORKSPACE"
    repair = f"Run `{repair_cmd}` to refresh native Skill adapters."

    try:
        target_path = preflight_workspace_paths(target_root)
        source_path = preflight_workspace_paths(work_area_root)
    except (PayloadError, OSError):
        return ()

    owned_entries: dict[str, bytes] = {}
    with WorkspaceAnchor(target_path) as target_anchor:
        for prefix in prefixes:
            try:
                candidates = _scan_prefix_skill_files(target_path, prefix)
            except SkillAdapterError:
                continue
            for rel in candidates:
                if excluded is not None and not is_project and excluded(rel):
                    continue
                try:
                    content, _ = target_anchor.read_file(rel)
                except OSError:
                    continue
                if owns_adapter(
                    content,
                    rel,
                    is_project=is_project,
                    expected_relative_workspace=relative_workspace,
                ):
                    owned_entries[rel] = content

    if not owned_entries:
        return ()

    ignored_names: set[str] = set()
    with WorkspaceAnchor(source_path) as source_anchor:
        try:
            qualifying = discover_qualifying_skills(
                source_anchor,
                excluded=excluded,
                ignored_names=ignored_names,
            )
        except SkillAdapterError:
            return ()

    expected: dict[str, bytes] = {}
    for skill in qualifying:
        canonical_rel = canonical_relative_path(
            skill.name,
            relative_workspace=relative_workspace if is_project else None,
        )
        rendered = render_adapter_bytes(skill.name, skill.description, canonical_rel)
        for prefix in prefixes:
            expected[f"{prefix}/{skill.name}/SKILL.md"] = rendered

    findings: list[AdapterFinding] = []
    for target_rel in sorted(expected):
        desired_bytes = expected[target_rel]
        if target_rel in owned_entries:
            if owned_entries[target_rel] != desired_bytes:
                findings.append(
                    AdapterFinding(
                        "skill-adapter-drift",
                        target_rel,
                        f"Generated native Skill adapter differs from its canonical Skill. {repair}",
                    )
                )
            continue
        try:
            state = _inspect_target_entry(target_path, target_rel)
        except SkillAdapterError:
            # Unrecognized or non-owned occupant is never an adapter finding.
            continue
        if state == "missing":
            findings.append(
                AdapterFinding(
                    "skill-adapter-missing",
                    target_rel,
                    f"Expected native Skill adapter is missing. {repair}",
                )
            )
        # If state is 'file' (not in owned_entries -> unrecognized) or 'occupant', never report a finding.

    for owned_rel in sorted(owned_entries):
        if owned_rel not in expected:
            parsed = parse_adapter_target(owned_rel, prefixes=prefixes)
            if parsed is not None and parsed[1] in ignored_names:
                continue
            if excluded is not None and excluded(learned_skills.ADOPTED):
                continue
            findings.append(
                AdapterFinding(
                    "skill-adapter-orphan",
                    owned_rel,
                    f"Generated native Skill adapter remains for a non-qualifying Skill. {repair}",
                )
            )

    return tuple(findings)
