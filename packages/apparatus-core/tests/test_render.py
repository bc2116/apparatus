def test_render_check_drift_loop_and_missing_hint(tmp_path):
    workspace = _checked_workspace(tmp_path / "workspace")
    before = check_workspace(workspace)
    assert {finding.code for finding in before.findings} == {"shim-missing"}
    assert all("apparatus render" in finding.hint for finding in before.findings)

    render_workspace(workspace)
    assert check_workspace(workspace).ok
    (workspace / "AGENTS.md").write_text("# Changed canon\n", encoding="utf-8")
    stale = check_workspace(workspace).findings
    assert [(finding.code, finding.path) for finding in stale] == [
        ("shim-drift", target) for target, _ in SHIM_REGISTRY
    ]
    render_workspace(workspace)
    assert check_workspace(workspace).ok


