def _workspace(path: Path, canon: bytes = b"# Workspace canon\n") -> Path:
    path.mkdir()
    (path / "AGENTS.md").write_bytes(canon)
    return path


def _checked_workspace(path: Path) -> Path:
    workspace = _workspace(path)
    (workspace / "Welcome.md").write_text("Welcome\n", encoding="utf-8")
    for relative in (
        "Goals",
        "Decisions",
        "Projects",
        "Library",
        "Deliverables",
        "Memory/People",
        "Memory/Facts",
        "System",
    ):
        (workspace / relative).mkdir(parents=True, exist_ok=True)
    return workspace


def _tree_state(root: Path) -> tuple[tuple[str, str, bytes | str | None], ...]:
    entries: list[tuple[str, str, bytes | str | None]] = []
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix()
        if path.is_symlink():
            entries.append((relative, "symlink", os.readlink(path)))
        elif path.is_file():
            entries.append((relative, "file", path.read_bytes()))
        else:
            entries.append((relative, "directory", None))
    return tuple(entries)


def test_render_is_deterministic_and_uses_raw_canon_bytes(tmp_path):
    canon = b"# Workspace canon\r\n\xff\n"
    workspace = _workspace(tmp_path / "workspace", canon)
    first = render_workspace(workspace)
    first_bytes = {shim.target: (workspace / shim.target).read_bytes() for shim in rendered_shims(workspace)}
    second = render_workspace(workspace)

    digest = hashlib.sha256(canon).hexdigest()
    assert set(first.written) == {target for target, _ in SHIM_REGISTRY}
    assert second.written == ()
    assert set(second.unchanged) == {target for target, _ in SHIM_REGISTRY}
    for target, content in first_bytes.items():
        assert digest.encode() in content
        assert b"Generated by apparatus render. Do not edit by hand." in content
        assert b"Edit AGENTS.md, then run apparatus render." in content


