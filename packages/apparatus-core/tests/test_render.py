def test_render_replaces_a_workspace_hardlink_without_mutating_its_other_name(tmp_path):
    workspace = _workspace(tmp_path / "workspace")
    outside = tmp_path / "outside.md"
    outside.write_bytes(b"outside sentinel")
    target = workspace / "CLAUDE.md"
    os.link(outside, target)
    outside_before = os.stat(outside)
    registry = (("CLAUDE.md", "claude-md.template"),)

    assert render_workspace(workspace, registry=registry).written == ("CLAUDE.md",)
    assert outside.read_bytes() == b"outside sentinel"
    assert os.stat(outside).st_ino == outside_before.st_ino
    assert os.stat(target).st_ino != outside_before.st_ino
    assert target.read_bytes() == rendered_shims(workspace, registry=registry)[0].content


