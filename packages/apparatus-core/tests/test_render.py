def test_render_command_exit_contract_and_status_lines(tmp_path, capsys):
    missing = tmp_path / "missing"
    assert render_command.run(argparse.Namespace(workspace=str(missing))) == 2
    assert "workspace path does not exist" in capsys.readouterr().out

    file_path = tmp_path / "file"
    file_path.write_text("x", encoding="utf-8")
    assert render_command.run(argparse.Namespace(workspace=str(file_path))) == 2
    assert "workspace path is not a directory" in capsys.readouterr().out

    workspace = _workspace(tmp_path / "workspace")
    assert render_command.run(argparse.Namespace(workspace=str(workspace))) == 0
    output = capsys.readouterr().out
    assert output.count("written ") == len(SHIM_REGISTRY)
    assert render_command.run(argparse.Namespace(workspace=str(workspace))) == 0
    assert capsys.readouterr().out.count("unchanged ") == len(SHIM_REGISTRY)

    no_canon = tmp_path / "no-canon"
    no_canon.mkdir()
    assert render_command.run(argparse.Namespace(workspace=str(no_canon))) == 2
    assert "missing AGENTS.md" in capsys.readouterr().out


