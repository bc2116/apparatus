def test_check_adapter_findings_gate_on_owned_adapters_and_ignore_unrecognized(tmp_path, capsys):
    area = _init_area(tmp_path / "area")
    # Remove all owned adapters -> zero owned adapters => zero adapter findings
    adapters.remove_owned_adapters(area, is_project=False)
    # Place an unrecognized file at an adapter path -> still 0 owned adapters => clean check
    unrecognized = area / ".claude/skills/apparatus-welcome/SKILL.md"
    unrecognized.parent.mkdir(parents=True)
    unrecognized.write_bytes(b"Unrecognized file")
    assert check_workspace(area).ok

    # Restore owned adapters while leaving apparatus-welcome as unrecognized -> >=1 owned adapters
    render_workspace(area)
    assert check_workspace(area).ok  # unrecognized occupant is NEVER a finding!

    # Adopt and render orphan candidate first before creating drift/missing
    _adopt_learned(area, "learned-orphan-test", "Orphan test.")
    render_workspace(area)
    # Drift: modify canonical description without rendering
    welcome = area / ".agents/skills/apparatus-economizer/SKILL.md"
    welcome.write_bytes(_skill_body("apparatus-economizer", "Updated canonical description."))
    # Missing: delete one owned adapter
    (area / ".claude/skills/apparatus-humanizer/SKILL.md").unlink()
    # Orphan: remove marker after rendering
    (area / learned.marker_path("learned-orphan-test")).unlink()

    findings = check_workspace(area).findings
    codes = {(f.code, f.path) for f in findings}
    assert ("skill-adapter-drift", ".claude/skills/apparatus-economizer/SKILL.md") in codes
    assert ("skill-adapter-missing", ".claude/skills/apparatus-humanizer/SKILL.md") in codes
    assert ("skill-adapter-orphan", ".claude/skills/learned-orphan-test/SKILL.md") in codes
    assert not any(f.path == ".claude/skills/apparatus-welcome/SKILL.md" for f in findings)

    # Now verify bound project check
    render_workspace(area)
    project = area / "project"
    project.mkdir()
    binding.bind_project(project, area)
    assert check_command.run(argparse.Namespace(workspace=str(project), no_receipt=True)) == 0
    capsys.readouterr()

    # Delete all project owned adapters -> 0 owned adapters => check PROJECT passes
    adapters.remove_owned_adapters(project, is_project=True, expected_relative_workspace="..")
    assert check_command.run(argparse.Namespace(workspace=str(project), no_receipt=True)) == 0
    capsys.readouterr()

    # Re-create project adapters, then create drift + missing + orphan in project
    _adopt_learned(area, "learned-proj-orphan", "Project orphan test.")
    binding.bind_project(project, area)
    (project / ".claude/skills/apparatus-humanizer/SKILL.md").unlink()
    (area / learned.marker_path("learned-proj-orphan")).unlink()
    (area / ".agents/skills/apparatus-economizer/SKILL.md").write_bytes(
        _skill_body("apparatus-economizer", "Project drift description.")
    )
    assert check_command.run(argparse.Namespace(workspace=str(project), no_receipt=True)) == 1
    proj_out = capsys.readouterr().out
    assert "skill-adapter-missing" in proj_out
    assert "skill-adapter-drift" in proj_out
    assert "skill-adapter-orphan" in proj_out


def test_unsafe_parent_symlink_windows_reserved_and_case_collisions_are_rejected(tmp_path):
    area = _init_area(tmp_path / "area")
    adapters.remove_owned_adapters(area, is_project=False)

    # 1. Parent symlink escape
    outside = tmp_path / "outside"
    outside.mkdir()
    try:
        (area / ".claude").symlink_to(outside, target_is_directory=True)
    except OSError as error:
        if os.name == "nt" and getattr(error, "winerror", None) == 1314:
            pass
        else:
            raise
    else:
        with pytest.raises(adapters.SkillAdapterError):
            adapters.sync_work_area_adapters(area)
        assert list(outside.iterdir()) == []
        (area / ".claude").unlink()

    # 2. Windows-reserved Skill name
    with pytest.raises(adapters.SkillAdapterError, match="Windows-reserved"):
        adapters.canonical_relative_path("con")

    # 3. Case mismatch on existing directory
    (area / ".Claude").mkdir()
    try:
        exact = any(e.name == ".Claude" for e in os.scandir(area))
    finally:
        pass
    if exact:
        with pytest.raises(adapters.SkillAdapterError, match="collides"):
            adapters.sync_work_area_adapters(area)


