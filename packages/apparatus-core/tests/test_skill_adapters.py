def test_unrecognized_occupants_are_preserved_report_conflicts_and_set_exit_codes(tmp_path, capsys):
    area = _init_area(tmp_path / "area")
    occupied_file = area / ".claude/skills/apparatus-welcome/SKILL.md"
    custom_bytes = b"User-authored custom adapter; must never be overwritten.\n"
    occupied_file.write_bytes(custom_bytes)

    occupied_dir = area / ".claude/skills/apparatus-economizer/SKILL.md"
    occupied_dir.unlink()
    occupied_dir.mkdir()
    (occupied_dir / "notes.txt").write_bytes(b"keep dir")

    # Symlink occupant on a target path when supported
    symlink_target = area / ".claude/skills/apparatus-humanizer/SKILL.md"
    outside = tmp_path / "outside.txt"
    outside.write_bytes(b"outside sentinel")
    symlink_target.unlink()
    has_symlink = True
    try:
        symlink_target.symlink_to(outside)
    except OSError as error:
        if os.name == "nt" and getattr(error, "winerror", None) == 1314:
            has_symlink = False
            symlink_target.write_bytes(custom_bytes)
        else:
            raise

    # render exits 1 on conflicts while still refreshing remaining targets
    (area / ".claude/skills/apparatus-weekly-review/SKILL.md").unlink()
    code = render_command.run(argparse.Namespace(workspace=str(area)))
    out = capsys.readouterr().out
    assert code == 1
    assert ".claude/skills/apparatus-welcome/SKILL.md" in out
    assert ".claude/skills/apparatus-economizer/SKILL.md" in out
    assert ".claude/skills/apparatus-humanizer/SKILL.md" in out
    assert occupied_file.read_bytes() == custom_bytes
    assert (occupied_dir / "notes.txt").read_bytes() == b"keep dir"
    assert outside.read_bytes() == b"outside sentinel"
    if has_symlink:
        assert symlink_target.is_symlink()
    assert (area / ".claude/skills/apparatus-weekly-review/SKILL.md").is_file()

    # init preserves exit 0 while reporting the same conflicts
    init_code = init_command.run(
        argparse.Namespace(workspace=str(area), payload=None, privacy_mode=None, work_types=None, adopt=False, task=None),
        available=lambda: False,
    )
    init_out = capsys.readouterr().out
    assert init_code == 0
    assert ".claude/skills/apparatus-welcome/SKILL.md" in init_out
    assert occupied_file.read_bytes() == custom_bytes

    # project bind preserves exit 0 while reporting project occupant conflicts
    project = area / "project"
    project.mkdir()
    proj_occupant = project / ".claude/skills/apparatus-welcome/SKILL.md"
    proj_occupant.parent.mkdir(parents=True)
    proj_occupant.write_bytes(custom_bytes)
    bind_code = project_command.run(
        argparse.Namespace(project_action="bind", project=str(project), workspace=str(area), replace=False)
    )
    bind_out = capsys.readouterr().out
    assert bind_code == 0
    assert ".claude/skills/apparatus-welcome/SKILL.md" in bind_out
    assert proj_occupant.read_bytes() == custom_bytes
    assert (project / ".agents/skills/apparatus-welcome/SKILL.md").is_file()


