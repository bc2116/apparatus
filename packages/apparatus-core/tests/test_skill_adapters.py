def test_concurrent_edit_compensates_only_owned_writes(tmp_path, monkeypatch):
    area = _init_area(tmp_path / "area")
    adapters.remove_owned_adapters(area, is_project=False)
    user_file = area / ".claude/user-note.txt"
    user_file.parent.mkdir(parents=True)
    user_file.write_bytes(b"preserve user note")

    original = WorkspaceAnchor.create_file
    calls = 0

    def fail_second(self, relative, content, *args, **kwargs):
        nonlocal calls
        if str(relative) == "SKILL.md":
            calls += 1
            if calls == 2:
                raise OSError("injected failure")
        return original(self, relative, content, *args, **kwargs)

    monkeypatch.setattr(WorkspaceAnchor, "create_file", fail_second)
    with pytest.raises(adapters.SkillAdapterError):
        adapters.sync_work_area_adapters(area)
    monkeypatch.setattr(WorkspaceAnchor, "create_file", original)
    assert user_file.read_bytes() == b"preserve user note"
    assert not (area / ".claude/skills").exists()


